const EmojiPicker = ({ visible, onClose, onEmojiSelect }) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState('smileys');
  const [recentEmojis, setRecentEmojis] = useState([]);

  // Load recent emojis from storage
  React.useEffect(() => {
    const loadRecentEmojis = async () => {
      try {
        const AsyncStorage = require('@react-native-async-storage/async-storage').default;
        const stored = await AsyncStorage.getItem('recentEmojis');
        if (stored) {
          setRecentEmojis(JSON.parse(stored));
        }
      } catch (error) {
        console.error('Error loading recent emojis:', error);
      }
    };
    if (visible) {
      loadRecentEmojis();
    }
  }, [visible]);

  // Save emoji to recent
  const saveToRecent = async (emoji) => {
    try {
      const AsyncStorage = require('@react-native-async-storage/async-storage').default;
      let updated = [emoji, ...recentEmojis.filter(e => e !== emoji)].slice(0, 30);
      setRecentEmojis(updated);
      await AsyncStorage.setItem('recentEmojis', JSON.stringify(updated));
    } catch (error) {
      console.error('Error saving recent emoji:', error);
    }
  };

  // Filter emojis based on search
  const filteredEmojis = useMemo(() => {
    if (!searchQuery.trim()) {
      if (selectedCategory === 'recent') {
        return recentEmojis;
      }
      return EMOJI_DATA[selectedCategory] || [];
    }

    // Search across all categories
    const query = searchQuery.toLowerCase();
    const allEmojis = Object.values(EMOJI_DATA).flat();
    return allEmojis.filter(emoji => {
      // Simple search - you can enhance this with emoji names/descriptions
      return emoji.includes(query) || emoji.charCodeAt(0).toString().includes(query);
    });
  }, [searchQuery, selectedCategory, recentEmojis]);

  const handleEmojiPress = (emoji) => {
    saveToRecent(emoji);
    if (onEmojiSelect) {
      onEmojiSelect(emoji);
    }
  };

  return (
    <Modal
      visible={visible}
      transparent={true}
      animationType="slide"
      onRequestClose={onClose}
    >
      <View style={styles.modalOverlay}>
        <View style={styles.container}>
          {/* Header */}
          <View style={styles.header}>
            <Text style={styles.headerTitle}>Emoji</Text>
            <TouchableOpacity onPress={onClose} style={styles.closeButton}>
              <Text style={styles.closeIcon}>✕</Text>
            </TouchableOpacity>
          </View>

          {/* Search Bar */}
          <View style={styles.searchContainer}>
            <TextInput
              style={styles.searchInput}
              placeholder="Search emoji..."
              placeholderTextColor={COLORS.inputPlaceholder}
              value={searchQuery}
              onChangeText={setSearchQuery}
            />
          </View>

          {/* Category Tabs */}
          <ScrollView 
            horizontal 
            showsHorizontalScrollIndicator={false}
            style={styles.categoryContainer}
            contentContainerStyle={styles.categoryContent}
          >
            {Object.entries(EMOJI_CATEGORIES).map(([key, category]) => {
              const isActive = selectedCategory === key;
              return (
                <TouchableOpacity
                  key={key}
                  style={[
                    styles.categoryTab,
                    isActive && styles.categoryTabActive
                  ]}
                  onPress={() => {
                    setSelectedCategory(key);
                    setSearchQuery('');
                  }}
                >
                  <Text style={[styles.categoryIcon, isActive && styles.categoryIconActive]}>
                    {category.icon}
                  </Text>
                  {isActive && (
                    <Text style={styles.categoryName}>{category.name}</Text>
                  )}
                </TouchableOpacity>
              );
            })}
          </ScrollView>

          {/* Emoji Grid */}
          <ScrollView style={styles.emojiContainer} contentContainerStyle={styles.emojiGrid}>
            {filteredEmojis.length > 0 ? (
              filteredEmojis.map((emoji, index) => (
                <TouchableOpacity
                  key={`${emoji}-${index}`}
                  style={styles.emojiItem}
                  onPress={() => handleEmojiPress(emoji)}
                  activeOpacity={0.7}
                >
                  <Text style={styles.emoji}>{emoji}</Text>
                </TouchableOpacity>
              ))
            ) : (
              <View style={styles.emptyContainer}>
                <Text style={styles.emptyText}>No emojis found</Text>
              </View>
            )}
          </ScrollView>
        </View>
      </View>
    </Modal>
  );
};

